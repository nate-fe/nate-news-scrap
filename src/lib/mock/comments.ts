/** 기사별 댓글 문구 목록. 기사 댓글과 일반 댓글을 번갈아 섞어서, 최신 20개 안에서는 겹치지 않게 한다. */
/** 기사마다 일반 댓글·작성자 순서가 달라 보이도록 쓰는 오프셋 */
function articleOffset(articleId: string): number {
  return Number(articleId.replace(/\D/g, "")) || 0;
}

function poolFor(articleId: string): string[] {
  const own = BY_ARTICLE[articleId] ?? [];
  const shift = articleOffset(articleId) * 5;
  const generic = GENERIC.map((_, i) => GENERIC[(i + shift) % GENERIC.length]);
  const pool: string[] = [];
  const max = Math.max(own.length, generic.length);
  for (let i = 0; i < max; i++) {
    if (i < own.length) pool.push(own[i]);
    if (i < generic.length && i % 2 === 0) pool.push(generic[i]);
  }
  // 일반 댓글 중 아직 안 쓴 것도 뒤에 붙인다
  for (let i = 1; i < generic.length; i += 2) pool.push(generic[i]);
  return pool;
}

export function mockCommentContent(articleId: string, index: number): string {
  const pool = poolFor(articleId);
  return pool[index % pool.length];
}

export function mockCommentAuthor(articleId: string, index: number): string {
  const i = (index * 7 + articleOffset(articleId) * 11) % AUTHOR_PREFIXES.length;
  return `${AUTHOR_PREFIXES[i]}****`;
}
